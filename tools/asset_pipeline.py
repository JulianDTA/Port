def print_summary(out_dir):
    total = 0
    for f in os.listdir(out_dir):
        if f.endswith(".h"):
            sz = os.path.getsize(os.path.join(out_dir, f))
            total += sz
    print(f"\n[SUMMARY] Generated C headers in {out_dir}")
    print(f"  Total header size: {total / 1024:.1f} KB")
    print(f"  Note: On NDS, only active textures should be loaded into VRAM at any time.")

if __name__ == "__main__":
    base = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    out = os.path.join(base, "include", "gfx")
    os.makedirs(out, exist_ok=True)

    print("=" * 50)
    print("  Balatro-DSi Asset Pipeline")
    print("=" * 50)

    process_deck(base, out)
    process_jokers(base, out)
    process_enhancers(base, out)
    print_summary(out)
