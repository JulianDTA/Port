#!/usr/bin/env python3
"""
Balatro-DSi Asset Pipeline
Converts original Balatro 1x textures into NDS-compatible formats:
  - Resizes sprites to fit 256x192 screens
  - Quantizes to indexed palettes (4bpp/8bpp)
  - Generates C headers with RGB555 palette data
  - Exports individual card sprites and Joker sprites
"""
import os
import sys
import struct
from PIL import Image

# NDS sprite dimensions (must be multiples of 8 for tile engine)
DS_CARD_W = 24
DS_CARD_H = 32
DS_JOKER_W = 24
DS_JOKER_H = 32

def rgb888_to_rgb555(r, g, b):
    return ((r >> 3) & 0x1F) | (((g >> 3) & 0x1F) << 5) | (((b >> 3) & 0x1F) << 10)

def slice_spritesheet(img, cols, rows):
    """Slice a spritesheet into individual cell images."""
    w, h = img.size
    cell_w = w // cols
    cell_h = h // rows
    cells = []
    for r in range(rows):
        for c in range(cols):
            box = (c * cell_w, r * cell_h, (c + 1) * cell_w, (r + 1) * cell_h)
            cells.append(img.crop(box))
    return cells, cell_w, cell_h

def build_ds_sheet(cells, cols, target_w, target_h):
    """Resize cells and composite into a new spritesheet."""
    rows = (len(cells) + cols - 1) // cols
    sheet = Image.new("RGBA", (cols * target_w, rows * target_h), (0, 0, 0, 0))
    for i, cell in enumerate(cells):
        r = i // cols
        c = i % cols
        resized = cell.resize((target_w, target_h), Image.Resampling.LANCZOS)
        sheet.paste(resized, (c * target_w, r * target_h))
    return sheet

def export_c_header(quantized_img, name, out_path, palette_size=256):
    """Export quantized indexed image as a C header with palette and pixel data."""
    palette_raw = quantized_img.getpalette()
    w, h = quantized_img.size
    pixels = list(quantized_img.getdata())

    with open(out_path, "w") as f:
        f.write(f"// Auto-generated by Balatro-DSi Asset Pipeline\n")
        f.write(f"// Source: {name}\n")
        f.write(f"#ifndef {name.upper()}_GFX_H\n#define {name.upper()}_GFX_H\n\n")
        f.write(f"#include <stdint.h>\n\n")
        f.write(f"#define {name.upper()}_WIDTH  {w}\n")
        f.write(f"#define {name.upper()}_HEIGHT {h}\n\n")

        # Palette (RGB555)
        f.write(f"static const uint16_t {name}_palette[{palette_size}] = {{\n")
        for i in range(palette_size):
            r = palette_raw[i * 3] if i * 3 < len(palette_raw) else 0
            g = palette_raw[i * 3 + 1] if i * 3 + 1 < len(palette_raw) else 0
            b = palette_raw[i * 3 + 2] if i * 3 + 2 < len(palette_raw) else 0
            c = rgb888_to_rgb555(r, g, b)
            f.write(f"  0x{c:04X},")
            if (i + 1) % 8 == 0:
                f.write("\n")
        f.write(f"}};\n\n")

        # Pixel data (8bpp = 1 byte per pixel)
        f.write(f"static const uint8_t {name}_pixels[{w * h}] = {{\n")
        for i, px in enumerate(pixels):
            f.write(f"0x{px:02X},")
            if (i + 1) % 16 == 0:
                f.write("\n")
        f.write(f"}};\n\n")
        f.write(f"#endif // {name.upper()}_GFX_H\n")

    print(f"  [C HEADER] {out_path} ({w}x{h}, {palette_size} colors, {w*h} bytes pixel data)")

def process_deck(base_dir, out_dir):
    """Process 8BitDeck.png -> DS card sprites."""
    src = os.path.join(base_dir, "extracted", "resources", "textures", "1x", "8BitDeck.png")
    if not os.path.exists(src):
        print(f"[SKIP] {src} not found")
        return

    print(f"[DECK] Processing {src}")
    img = Image.open(src).convert("RGBA")
    w, h = img.size
    # 8BitDeck: 923x380 -> 13 columns (A through K) x 4 rows (suits) + extra right column
    # Actual card cell: 71x95 pixels per card
    cols = 13
    rows = 4
    cells, cw, ch = slice_spritesheet(img, cols, rows)
    print(f"  Original cell size: {cw}x{ch}, Total cards: {len(cells)}")

    ds_sheet = build_ds_sheet(cells, cols, DS_CARD_W, DS_CARD_H)
    preview = os.path.join(out_dir, "ds_deck_preview.png")
    ds_sheet.save(preview)
    print(f"  [PREVIEW] {preview}")

    quantized = ds_sheet.convert("P", palette=Image.Palette.ADAPTIVE, colors=256)
    quantized.save(os.path.join(out_dir, "ds_deck_quantized.png"))
    export_c_header(quantized, "deck", os.path.join(out_dir, "deck_gfx.h"))

